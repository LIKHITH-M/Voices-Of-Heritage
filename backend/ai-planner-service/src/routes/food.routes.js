// GET /api/food/trails
router.get('/trails', (req, res) => {
  const { region } = req.query;
  if (region && region !== 'All') {
    return res.json(culinaryTrails.filter((t) => t.region.toLowerCase() === region.toLowerCase()));
  }
  return res.json(culinaryTrails);
});

// GET /api/food/recipes
router.get('/recipes', (req, res) => {
  const { region, category } = req.query;
  let result = recipes;
  if (region && region !== 'All') {
    result = result.filter((r) => r.region.toLowerCase() === region.toLowerCase());
  }
  if (category && category !== 'All') {
    result = result.filter((r) => r.category.toLowerCase() === category.toLowerCase());
  }
  return res.json(result);
});

// GET /api/food/regions
router.get('/regions', (req, res) => {
  return res.json(regions);
});

// GET /api/food/stories
router.get('/stories', (req, res) => {
  return res.json(stories);
});

