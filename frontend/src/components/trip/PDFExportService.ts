/**
 * frontend/src/components/trip/PDFExportService.ts
 *
 * Client-side PDF Generation for VoH Itineraries (adapted from AI-TripPlanner-main).
 * Generates a clean, printable PDF document summarizing trip specifications,
 * day-by-day schedule, heritage notes, and research provenance.
 */

import jsPDF from 'jspdf';

interface ExportTripOptions {
  destination: string;
  duration: number;
  startDate?: string;
  endDate?: string;
  travelers?: number;
  budget?: string;
  totalEstimatedCost?: { amount: number; currency: string };
  heritageTheme?: string;
  personalizationSummary?: string;
  itinerary: any[];
  depkgMeta?: any;
}

export function exportItineraryToPDF(options: ExportTripOptions) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  let yPos = 20;

  // Header Banner
  doc.setFillColor(180, 119, 59); // Amber / Gold theme
  doc.rect(0, 0, pageWidth, 35, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(options.destination || 'Heritage Tour', pageWidth / 2, 16, { align: 'center' });

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  const subtitle = `Voices of Heritage · ${options.duration || 3}-Day Personalized Itinerary`;
  doc.text(subtitle, pageWidth / 2, 25, { align: 'center' });

  yPos = 45;
  doc.setTextColor(30, 30, 30);

  // Trip Specifications Box
  doc.setFillColor(245, 245, 247);
  doc.roundedRect(14, yPos, pageWidth - 28, 26, 3, 3, 'F');

  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('Trip Overview & Budget:', 18, yPos + 8);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  const costStr = options.totalEstimatedCost
    ? `${options.totalEstimatedCost.currency} ${options.totalEstimatedCost.amount.toLocaleString('en-IN')}`
    : 'Estimated based on monument fees';
  const datesStr = (options.startDate && options.endDate)
    ? `${options.startDate} to ${options.endDate}`
    : `${options.duration} days`;

  doc.text(`• Dates: ${datesStr}`, 18, yPos + 15);
  doc.text(`• Travelers: ${options.travelers || 2}`, 18, yPos + 21);
  doc.text(`• Estimated Total: ${costStr}`, 100, yPos + 15);
  const modeStr = options.depkgMeta?.mode === 'research'
    ? 'Mode B: Dynamic PTKG (Personalized)'
    : 'Mode A: Baseline';
  doc.text(`• Planner Mode: ${modeStr}`, 100, yPos + 21);

  yPos += 34;

  // Heritage Theme
  if (options.heritageTheme) {
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(9);
    doc.setTextColor(100, 100, 100);
    doc.text(`Theme: "${options.heritageTheme}"`, 14, yPos);
    yPos += 8;
  }

  // Daily Itinerary
  options.itinerary.forEach((dayPlan: any) => {
    if (yPos > pageHeight - 35) {
      doc.addPage();
      yPos = 20;
    }

    // Day Header
    doc.setFillColor(240, 230, 215);
    doc.rect(14, yPos, pageWidth - 28, 7, 'F');
    doc.setFontSize(10);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(140, 80, 20);
    doc.text(`Day ${dayPlan.day || 1}: ${dayPlan.title || 'Heritage Exploration'}`, 17, yPos + 5);
    yPos += 11;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(30, 30, 30);

    const activities = dayPlan.activities || [];
    activities.forEach((act: any) => {
      if (yPos > pageHeight - 25) {
        doc.addPage();
        yPos = 20;
      }

      const timeStr = act.time ? `[${act.time}] ` : '';
      const actTitle = `${timeStr}${act.activity || act.name || 'Activity'}`;
      doc.setFont('helvetica', 'bold');
      doc.text(actTitle, 18, yPos);

      const feeStr = act.cost?.amount ? `₹${act.cost.amount}` : (typeof act.cost === 'number' && act.cost > 0 ? `₹${act.cost}` : 'Free');
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(100, 100, 100);
      doc.text(feeStr, pageWidth - 22, yPos, { align: 'right' });
      doc.setTextColor(30, 30, 30);
      yPos += 4.5;

      const note = act.heritage_note || act.note || act.description;
      if (note) {
        doc.setFontSize(7.5);
        doc.setTextColor(80, 80, 80);
        const splitLines = doc.splitTextToSize(note, pageWidth - 40);
        doc.text(splitLines, 22, yPos);
        yPos += (splitLines.length * 3.5) + 2;
        doc.setFontSize(8.5);
        doc.setTextColor(30, 30, 30);
      } else {
        yPos += 2;
      }
    });

    yPos += 4;
  });

  // Footer on final page
  if (yPos > pageHeight - 20) {
    doc.addPage();
    yPos = 20;
  }
  doc.setFontSize(7);
  doc.setTextColor(140, 140, 140);
  doc.text('Generated by Voices of Heritage (VoH) — Dynamic Personal Travel Knowledge Graph System', pageWidth / 2, pageHeight - 8, { align: 'center' });

  // Save the PDF
  const filename = `${options.destination.replace(/[^a-zA-Z0-9]/g, '_')}_Itinerary.pdf`;
  doc.save(filename);
}

